"""Wireless adaptation of the copied TKG-DTN NetworkRAGAgent.

Generated by tools/adapt_tkg_agent.py. Original source and provenance live in
the TKG-DTN source; the parent rag_system_agent.py is never imported or modified.
"""

from __future__ import annotations

import json
import logging
import re
from typing import Dict, Optional, Tuple

from .tools import TOOL_HELP
from .model_view import compact_schema

logger = logging.getLogger(__name__)


class NetworkRAGAgent:
    def __init__(self, llm, tools, max_iterations=8, memory_handler=None):
        self.llm = llm
        self.tools = tools
        self.max_iterations = max_iterations
        self.memory_handler = memory_handler
        self.chat_history = []
        self.graph_schema = json.dumps(compact_schema(tools.graph.schema()), ensure_ascii=False, separators=(",", ":"))

    def _decide_next_action(self, question, scratchpad):
        memory = self.memory_handler.retrieve(question) if self.memory_handler else ""
        prompt = f"""You are the TKG-DTN wireless network agent. Follow Thought -> Action -> Observation.
The task is sequential user admission into eMBB or URLLC, with resource allocation.
The program has already read this user's current graph context into the observations.
Use it directly; get_decision_context is available when a refresh or full intent KB is needed.
Use the supplied intent knowledge and the request to select the appropriate slice.
Plan suitable integer bandwidth for the request, respecting slice QoS and capacity.
Prefer plan_allocation without bandwidth: it computes exact feasible allocation and optimizes
throughput for retained users. It needs no nested LLM or guessed bandwidth numbers.
If a plan is invalid, inspect its feasibility certificate; get_bandwidth_options lists all choices.
Do not change a user's service category just to admit them, or reject when a feasible plan exists.
Use plan_reallocation/commit_reallocation if existing assignments need repair or optimization.
Commit a valid plan, or reject with a specific reason if no suitable allocation is possible.
Never invent measurements, ground-truth labels, plan IDs, or successful tool outcomes.
The tools use the original simplified CQI-to-rate model. Latency is assigned, not measured.
Schema maps source types to [relationship,target] pairs in this run's real Neo4j graph.
The complete intent KB remains available in every round, alongside the decision evidence.

Tools:
{TOOL_HELP}

Graph Schema:
{self.graph_schema}

Memory: {memory or '(none)'}
Question: {question}
Observations from this request:
{scratchpad or '(none yet)'}

Return exactly one next action as:
思考: <brief decision rationale>
行动: {{"tool": "tool_name", "args": {{}}}}
"""
        return self.llm.complete([
            {"role": "system", "content": "You are a graph-grounded wireless resource agent. Use only observed facts and the listed tools."},
            {"role": "user", "content": prompt},
        ])

    def _run_tool(self, action):
        return self.tools.call(action.get("tool"), action.get("args", {}) or {})

    def _generate_final_answer(self, question, thought_trace):
        # Execution truth comes from the committed tool result. Do not ask an
        # extra LLM to invent an executable allocation in a natural-language answer.
        if self.tools.result is None:
            raise RuntimeError("ReAct ended without a committed allocation or explicit rejection")
        self.last_trace = thought_trace
        return json.dumps(self.tools.result, ensure_ascii=False)

    def ask_stream(self, question: str):
        context, summary = self.tools.call("get_decision_context", {}, origin="program_prefetch")
        if "error" in context:
            raise RuntimeError("Initial graph context unavailable: " + context["error"])
        scratchpad = "Program-prefetched graph context: " + summary
        full_trace = "Program-prefetched graph context: " + json.dumps(context, ensure_ascii=False)
        yield self._format_event("status", "已读取当前图谱上下文")
        latest_subgraph: Dict[str, object] = {}

        for iteration in range(self.max_iterations):
            yield self._format_event("status", f"--- 第 {iteration + 1} 轮思考 ---")
            llm_output = self._decide_next_action(question, scratchpad)

            try:
                thought, action = self._parse_llm_action(llm_output)
            except ValueError as exc:
                error_msg = f"解析 LLM 响应失败: {exc}. 原始响应: {llm_output}"
                yield self._format_event("error", error_msg)
                full_trace += f"\n思考: {llm_output}\n观察: {error_msg}"
                break

            yield self._format_event("status", f"思考: {thought}")

            if action.get("tool") == "finish":
                full_trace += f"\n思考: {thought}\n行动: {json.dumps(action, ensure_ascii=False)}"
                break

            tool_result, observation_summary = self._run_tool(action)
            full_trace += (
                f"\n思考: {thought}\n行动: {json.dumps(action, ensure_ascii=False)}"
                f"\n观察: {json.dumps(tool_result, ensure_ascii=False)}"
            )
            scratchpad += (
                f"\n思考: {thought}\n行动: {json.dumps(action, ensure_ascii=False)}"
                f"\n观察: {observation_summary}"
            )
            yield self._format_event("status", f"观察: {observation_summary}")

            if (
                action.get("tool") in ("execute_cypher", "Network_topology_query")
                and isinstance(tool_result, dict)
                and tool_result.get("subgraph", {}).get("nodes")
            ):
                latest_subgraph = tool_result.get("subgraph", latest_subgraph)

            if self.tools.result is not None:
                break

        yield self._format_event("status", "正在返回已执行的网络决策...")
        final_answer = self._generate_final_answer(question, full_trace)
        self.chat_history.append({"question": question, "answer": final_answer})
        yield self._format_event("final_answer", final_answer)

        # 保存记忆（如果配置了 Memory Handler）
        if self.memory_handler and hasattr(self.memory_handler, "save"):
            try:
                self.memory_handler.save(question=question, answer=final_answer, trace=full_trace)
            except Exception as e:
                logger.warning(f"Memory save failed: {e}")

        # if latest_subgraph:
        #     yield self._format_event("subgraph", latest_subgraph)

        yield self._format_event("end", None)

    def _format_event(self, event_type: str, data: Optional[object]) -> str:
        return f"data: {json.dumps({'type': event_type, 'data': data}, ensure_ascii=False)}\n\n"

    def _parse_llm_action(self, llm_output: str) -> Tuple[str, Dict[str, object]]:
        # 兼容中文冒号，避免解析错误
        llm_output = llm_output.replace("行动：", "行动:").replace("思考：", "思考:")
        
        if "行动:" not in llm_output:
            raise ValueError("缺少 '行动:' 关键字")
        thought = llm_output.split("行动:", 1)[0].replace("思考:", "").strip()
        action_text = llm_output.split("行动:", 1)[1].strip()
        match = re.search(r"\{.*\}", action_text, re.DOTALL)
        if not match:
            raise ValueError("行动部分未解析出合法 JSON")
        action = json.loads(match.group())
        return thought, action

